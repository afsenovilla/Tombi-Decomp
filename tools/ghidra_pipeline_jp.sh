#!/usr/bin/env bash
# Ghidra pipeline (headless) for the JAPANESE retail disc (SLPS-01144). Same idea as tools/ghidra_pipeline.sh.
#   tools/ghidra_pipeline_jp.sh import   imports + analyzes SLPS_011.44, X00, X10, X11, X16, X17 and INFO2 (once)
#   tools/ghidra_pipeline_jp.sh apply    creates functions/names from tools/jp_syms.py prep and exports funcs + decompilation
# Needs game_jp/{SLPS_011.44,SYSTEM/X*.BIN,SYSTEM/INFO2.BIN} (python3 tools/jp_syms.py extract). Nothing here is committed:
# PROJ (default /opt/gproj_jp) and OUT (default /opt/gproj_jp/out) live outside git.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GHIDRA="${GHIDRA:-/opt/tools/ghidra_12.1.4_PUBLIC}"
PROJ="${PROJ:-/opt/gproj_jp}"
OUT="${OUT:-$PROJ/out}"
IN="${IN:-$PROJ/in}"            # generated by: python3 tools/jp_syms.py prep $IN
RUN="$GHIDRA/support/analyzeHeadless $PROJ tombijp"
SCRIPTS="$ROOT/ghidra/scripts"
OVL="${OVL:-X00 X10 X11 X16 X17}"
BASE=800e9af8                   # JP overlay base (config/slps01144/x*.yaml)

do_import() {
  mkdir -p "$PROJ"
  $RUN -import "$ROOT/game_jp/SLPS_011.44" -overwrite -analysisTimeoutPerFile 900
  for x in $OVL; do
    $RUN -import "$ROOT/game_jp/SYSTEM/$x.BIN" -overwrite -loader BinaryLoader -loader-baseAddr $BASE \
         -processor "MIPS:LE:32:default" -analysisTimeoutPerFile 900
  done
  $RUN -import "$ROOT/game_jp/SYSTEM/INFO2.BIN" -overwrite -loader BinaryLoader -loader-baseAddr $BASE \
       -processor "MIPS:LE:32:default" -analysisTimeoutPerFile 900
}

apply_one() {   # program, tag
  $RUN -process "$1" -noanalysis -scriptPath "$SCRIPTS" \
       -postScript CreateFunctionsRange.java "$IN/$2.funcs" \
       -postScript ImportNames.java "$IN/$2.csv" \
       -postScript ExportFuncs.java "$OUT/$2.funcs.csv" \
       -postScript ExportAll.java "$OUT"
}

do_apply() {
  mkdir -p "$OUT"
  apply_one SLPS_011.44 slps01144
  for x in $OVL; do apply_one "$x.BIN" "$(echo "$x" | tr A-Z a-z)"; done
  apply_one INFO2.BIN info2
}

case "${1:-all}" in
  import) do_import ;;
  apply)  do_apply ;;
  all)    do_import; do_apply ;;
  *) echo "usage: $0 import|apply|all"; exit 1 ;;
esac
