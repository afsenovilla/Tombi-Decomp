#!/usr/bin/env python3
"""Generate port2/runtime/colview_exits.inc from tools/colview_exits.json.

The JSON lists the side-view room exit trigger boxes found in the area overlays
(tryStartItemInteraction calls in updateAreaScroll and friends). Each entry has
area, sections, exit, h/y/d ranges (null = unbounded) and the extra condition
text (cond). The collision view (--show-collision) draws these boxes.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "colview_exits.json")
DST = os.path.join(ROOT, "port2", "runtime", "colview_exits.inc")


def rng(v):
    if v is None:
        return -32768, 32767
    return max(-32768, v[0]), min(32767, v[1])


def main():
    data = json.load(open(SRC))
    out = ["/* generated by tools/colview_exits.py from tools/colview_exits.json:",
           "   area, exit, cond, section mask, h0, h1, y0, y1, d0, d1 */"]
    for e in sorted(data, key=lambda e: (e["area"], min(e["sections"]), e["exit"])):
        mask = 0
        for s in e["sections"]:
            mask |= 1 << s
        cond = 1 if e["cond"] and e["cond"] != "mode 2 call" else 0
        h, y, d = rng(e["h"]), rng(e["y"]), rng(e["d"])
        out.append("{ %d, %d, %d, 0x%Xu, %d, %d, %d, %d, %d, %d }, /* %s:%d */"
                   % (e["area"], e["exit"], cond, mask, *h, *y, *d, e["file"], e["line"]))
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(DST) and open(DST).read() == text
        print("up to date" if ok else "stale")
        return 0 if ok else 1
    open(DST, "w").write(text)
    print("%d exits -> %s" % (len(data), DST))
    return 0


if __name__ == "__main__":
    sys.exit(main())
