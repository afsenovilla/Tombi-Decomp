#!/usr/bin/env python3
"""Writes config/slpm80165/reuse.txt: which PAL C function builds each demo function (Japanese demo, docs/JPDEMO.md).

For every demo function (the target objects of `tools/build_report.py --version slpm80165`, build/slpm80165/target/) the PAL
functions that have C (src files of tools/units.py, whole-file range) and the same size are compared word by word,
ignoring only the bits the demo object relocates (jal targets, %hi/%lo halves). Immediates such as struct offsets and
constants must be equal, unlike tools/xmatch.py, whose looser mask can pair a demo function with the wrong PAL twin.
One line per pair, by address so PAL file renames do not matter:

    <demo prog> <demo addr> <PAL module> <PAL addr>   # demo name = PAL file stem

build_report reads this file first and falls back to the PAL pairing in config/slpm80165/symbol_addrs_*.txt.
Needs the PAL game files (game/) and a previous demo report build; the output is committed, so CI does not.

  python3 tools/build_report.py --version slpm80165 && python3 tools/jpdemo_reuse.py && python3 tools/build_report.py --version slpm80165 --no-split

Japanese retail (docs/JP.md): the same with --version slps01144 on all three commands (writes config/slps01144/reuse.txt).
"""
import collections, os, re, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import units as U, xmatch as X
from versions import version_arg

RELMASK = {"R_MIPS_26": 0x3FFFFFF, "R_MIPS_HI16": 0xFFFF, "R_MIPS_LO16": 0xFFFF, "R_MIPS_32": 0xFFFFFFFF}


def text_and_relocs(obj, tmp):
    subprocess.run(["mipsel-linux-gnu-objcopy", "-O", "binary", "-j", ".text", obj, tmp], check=True)
    b = open(tmp, "rb").read()
    rel = {}
    for l in subprocess.run(["mipsel-linux-gnu-objdump", "-r", "-j", ".text", obj], capture_output=True, text=True).stdout.splitlines():
        m = re.match(r"([0-9a-f]{8})\s+(R_MIPS_\w+)", l)
        if m: rel[int(m.group(1), 16)] = RELMASK.get(m.group(2), 0xFFFFFFFF)
    return b, rel


def main():
    os.chdir(ROOT)
    ver = version_arg(sys.argv)
    src = {(p.lower(), u.addr): u for p, us in U.units().items() for u in us if u.file}
    bylen = collections.defaultdict(list)
    for mod, name, a, s, mw, fb in X.pal_funcs(ROOT):
        u = src.get((mod, a))
        if u and u.size == s: bylen[s].append((mod, a, fb))
    tmp = tempfile.mktemp(suffix=".bin")
    lines = []
    for prog in sorted(os.listdir("build/%s/target" % ver)):
        asmdir = "asm/%s/%s/nonmatchings/%s" % (ver, prog, prog)
        for fn in sorted(os.listdir("build/%s/target/%s" % (ver, prog))):
            name = fn[:-2]
            sf = "%s/%s.s" % (asmdir, name)
            if not os.path.exists(sf): continue  # data.o: a data object, not a function (no nonmatchings asm)
            am = re.search(r"/\* [0-9A-F]+ ([0-9A-F]{8}) ", open(sf).read())
            if not am: continue
            b, rel = text_and_relocs("build/%s/target/%s/%s" % (ver, prog, fn), tmp)
            n = len(b) // 4
            mk = [0xFFFFFFFF & ~rel.get(4 * i, 0) for i in range(n)]
            tw = [w & m for w, m in zip(X.words(b), mk)]
            hits = [(mod, a) for mod, a, fb in bylen.get(len(b), ()) if [w & m for w, m in zip(X.words(fb), mk)] == tw]
            if hits:  # prefer MAIN0 / X000 over area overlay copies, then the lowest address
                mod, a = sorted(hits, key=lambda h: (h[0] not in ("main0", "x000"), h[0], h[1]))[0]
                lines.append("%s %s %s %08X  # %s" % (prog, am.group(1), mod, a, name))
    os.unlink(tmp)
    hdr = "# %s prog, %s address, PAL module, PAL address (generated by tools/jpdemo_reuse.py; see its docstring)\n" % (ver, ver)
    open("config/%s/reuse.txt" % ver, "w").write(hdr + "\n".join(lines) + "\n")
    print("config/%s/reuse.txt: %d pairs" % (ver, len(lines)))


def spad():
    """--spad: writes config/slpm80165/spad.txt, the PAL scratchpad symbols (0x1F80xxxx PROVIDEs of a PAL
    tools/build_full.py link, build/full/*.full.ld). build_report assembles them as constants for the demo."""
    os.chdir(ROOT)
    tab = {}
    for f in sorted(os.listdir("build/full")):
        if f.endswith(".full.ld"):
            for n, a in re.findall(r"PROVIDE\((\w+) = 0x(1F80[0-9A-F]{4})\);", open("build/full/" + f).read()):
                if "__" not in n: tab[n] = a  # name__ADDR: a name build_full split by address
    hdr = ("# PAL scratchpad symbols (name, address) from build/full/*.full.ld, written by tools/jpdemo_reuse.py --spad: the demo\n"
           "# report assembles them as constants, since the demo target keeps scratchpad addresses literal.\n")
    open("config/slpm80165/spad.txt", "w").write(hdr + "".join("%s %s\n" % (n, tab[n]) for n in sorted(tab)))
    print("config/slpm80165/spad.txt: %d symbols" % len(tab))


if __name__ == "__main__":
    spad() if "--spad" in sys.argv else main()
