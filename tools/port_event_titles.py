#!/usr/bin/env python3
"""Port-only event titles for the events PAL leaves without one (MAIN0 table 0x80080410 = 0xFF), translated from the
Japanese release's per-area title lists (notes/secrets.md "Event titles in other versions").

Writes port2/shims/port_event_titles.h: for each language file CFNT999{B,F,G,I,H,S,P,W,D} the glyph words of every
title (letters only: banner texts carry no spaces, the layout list places the words) and its word lengths ('/' = line).
English text is used for the languages other than Spanish when that file's font has every letter; otherwise the
event keeps no title there.  Glyph indices are read from the disc (no game data is written, only indices).

  python3 tools/port_event_titles.py [DISC]      (default game/disc/Tombi.bin)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# event: (English, Spanish); '/' = line break.  Source: JP title (tools/event_titles.py, jp_text dump).
TITLES = {
    6:   ("A Big/Puddle?", "¿Un gran/charco?"),                       # 大きな水たまり？
    18:  ("The Dwarves'/Help", "La ayuda de/los Enanos"),             # ドワーフの助け
    45:  ("AP Slot/Machine", "Tragaperras/de AP"),                    # ＡＰスロットマシーン
    52:  ("No Way/Across...", "Ya no se/puede cruzar..."),            # 渡れなくなっちゃった…
    59:  ("The Chief's/Favor?", "¿El encargo/del jefe?"),             # 族長のたのみごと？
    60:  ("Masakari/Language", "Idioma/Masakari"),                    # コトバを吸いとろう！Ⅱ (learn the Masakari words)
    61:  ("The Masakari/Secret", "El secreto/Masakari"),              # マサカリ族のヒミツ
    67:  ("Decipher? The/Graffiti Rock", "¿Descifrar? La/roca garabateada"),  # 解読？らくがき岩
    74:  ("Catch the/Electric Eel!", "¡Atrapa la/anguila/eléctrica!"),        # 電気うなぎを捕まえろ！
    89:  ("The Green/Fortune Teller", "El adivino/verde"),            # 緑の占い師 (PAL #69/#125 style)
    94:  ("Let's Get/Along", "Llevémonos/bien"),                      # 仲良くしようよ
    95:  ("The Wood/Village's/Big Rock", "La gran roca del/pueblo de madera"),  # 木人の村の大岩
    96:  ("The Unfinished/Bridge...", "El puente sin/terminar..."),   # 未完の橋…
    97:  ("The Stopped/Clock Tower", "La torre del/reloj parada"),    # 動かない時計台 (0x61)
    98:  ("An Unbreakable/Gear?", "¿Un engranaje/irrompible?"),       # こわれない歯車？ (0x62)
    99:  ("Where's the/Material!?", "¡¿Dónde está/el material?!"),    # 材料はどこだ！？ (0x63)
    100: ("The Iron/Keyhole", "La cerradura/de hierro"),              # 鉄のカギ穴
    138: ("Catch Me If/You Can", "Atrápame si/puedes"),               # つかまえてごらん
    139: ("The Three Sisters'/Hide and Seek", "El escondite de/las tres hermanas"),  # ３姉妹のかくれんぼ
    140: ("A Letter to the/Three Sisters", "Carta para las/tres hermanas"),       # ３姉妹への手紙
    184: ("Am I a/Bad Kid?", "¿Soy un/niño malo?"),                   # おいら、悪い子？
    186: ("The Masakari/Village?", "¿La aldea/Masakari?"),            # マサカリの集落？
}
LINKS = {76: 90, 83: 126}     # existing CFNT999 texts no event points to (JP: 黒い水の不思議 / 動かない鉄の車)
LETTERS = "BFGIHSPWD"


def layout(text):
    return "/".join(" ".join(str(len(w)) for w in line.split()) for line in text.split("/"))


def main():
    import text_core as C
    disc = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "game/disc/Tombi.bin")
    p = C.Project(C.Source(disc))
    base = [x for x in p.src.files if x.upper().endswith("CFNT999B.WFM")][0][:-5]
    out = ["/* generated by tools/port_event_titles.py: port-only event titles (see the tool) */",
           "static const unsigned char port_et_events[] = { %s };" % ", ".join(str(e) for e in TITLES),
           "#define PORT_ET_N %d" % len(TITLES)]
    tabs = []
    for li, L in enumerate(LETTERS):
        w = p.wfm(base + L + ".WFM")
        rows = []
        for e, (en, es) in TITLES.items():
            text = es if L == "S" else en
            ids = []
            for ch in text.replace(" ", "").replace("/", ""):
                c = w.charidx.get(ch)
                if not c:
                    ids = None; break
                ids.append(0x8000 | c[0])
            if ids is None:
                rows.append("{ 0, 0 }")
                print("%s: event %d has no title (missing letters)" % (L, e))
                continue
            name = "port_et_%s_%d" % (L, e)
            out.append("static const unsigned short %s[] = { %s, 0xFFFF };" % (name, ", ".join("0x%04X" % v for v in ids)))
            rows.append('{ %s, "%s" }' % (name, layout(text)))
        tabs.append("    { " + ", ".join(rows) + " }")
    out.append("static const struct { const unsigned short *w; const char *lay; } port_et_tab[9][PORT_ET_N] = {\n%s\n};" % ",\n".join(tabs))
    open(os.path.join(ROOT, "port2/shims/port_event_titles.h"), "w").write("\n".join(out) + "\n")
    print("wrote port2/shims/port_event_titles.h")


if __name__ == "__main__":
    main()
