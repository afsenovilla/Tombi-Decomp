#!/usr/bin/env python3
"""Writes port2/runtime/panel_font.h: the second-screen panel's fonts (runtime/panel.c), Latin-1 32..255 rasterised
from Inter (SIL Open Font License 1.1, https://rsms.me/inter/) at the sizes below, 4-bit coverage.  No game data.

  python3 port2/tools/gen_panel_font.py [FONTDIR]     (default /usr/share/fonts/opentype/inter)
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [("body", "Inter-Medium.otf", 17), ("bold", "Inter-Bold.otf", 19), ("big", "Inter-Bold.otf", 26), ("small", "Inter-Medium.otf", 14)]


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"
    out = ["/* generated by port2/tools/gen_panel_font.py: Inter (SIL OFL 1.1, rsms.me/inter), Latin-1 32..255, 4-bit coverage */",
           "typedef struct { signed char ox, oy; unsigned char w, h, adv; unsigned off; } PanelGlyph;",
           "typedef struct { int asc, line; const PanelGlyph *g; const unsigned char *bits; } PanelFont;"]
    for name, fn, size in FONTS:
        f = ImageFont.truetype(os.path.join(d, fn), size)
        asc, desc = f.getmetrics()
        glyphs, bits = [], bytearray()
        for c in range(32, 256):
            ch = chr(c)
            if 127 <= c < 160:
                glyphs.append((0, 0, 0, 0, 0, len(bits))); continue
            adv = int(round(f.getlength(ch)))
            box = f.getbbox(ch)
            w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
            off = len(bits)
            if w and h:
                im = Image.new("L", (w, h), 0)
                ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
                px = list(im.tobytes())
                px += [0] * (len(px) & 1)
                for i in range(0, len(px), 2):
                    bits.append((px[i] + 8) // 17 | ((px[i + 1] + 8) // 17) << 4)
            glyphs.append((box[0], box[1], w, h, adv, off))
        out.append("static const PanelGlyph pf_%s_g[224] = {%s};" % (name, ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs)))
        rows = [",".join(str(b) for b in bits[i:i + 40]) for i in range(0, len(bits), 40)]
        out.append("static const unsigned char pf_%s_bits[%d] = {\n%s};" % (name, len(bits), ",\n".join(rows)))
        out.append("static const PanelFont pf_%s = { %d, %d, pf_%s_g, pf_%s_bits };" % (name, asc, asc + desc, name, name))
    p = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "panel_font.h")
    open(p, "w").write("\n".join(out) + "\n")
    print(p)


if __name__ == "__main__":
    main()
