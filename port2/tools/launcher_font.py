def main():
    bold = sys.argv[1] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    book = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
    out = ["/* Generated by port2/tools/launcher_font.py: DejaVu Sans glyphs for the 3DS start screen (n3ds/launcher_ui.c).",
           "   " + LICENSE + " */",
           "#include \"launcher_font.h\"", ""]
    fonts = []
    for k, (style, size) in enumerate(SIZES):
        f = ImageFont.truetype(bold if style == "bold" else book, size)
        asc, desc = f.getmetrics()
        data = bytearray(); glyphs = []
        for c in range(32, 256):
            ch = bytes([c]).decode("latin-1")
            if 127 <= c < 160: glyphs.append((0, 0, 0, 0, 0, 0)); continue
            adv = round(f.getlength(ch))
            im = Image.new("L", (size * 3, size * 3), 0)
            ImageDraw.Draw(im).text((size, 0), ch, font=f, fill=255)   # (the pen at x = size, the line's top at y = 0)
            box = im.getbbox()                                          # the ink, or None
            off = len(data); px = []; w = h = 0; bx = by = 0
            if box:
                bx, by, w, h = box[0] - size, box[1], box[2] - box[0], box[3] - box[1]
                im = im.crop(box)
                px = [im.getpixel((x, y)) >> 4 for y in range(h) for x in range(w)]
            if len(px) % 2: px.append(0)
            for i in range(0, len(px), 2): data.append(px[i] | px[i + 1] << 4)
            glyphs.append((adv, bx, by, w, h, off))
        name = "lf_%s%d" % (style, size)
        out.append("static const unsigned char %s_data[%d] = {" % (name, max(1, len(data))))
        for i in range(0, len(data), 24): out.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        if not data: out.append("    0,")
        out.append("};")
        out.append("static const LfGlyph %s_glyphs[224] = {" % name)
        for g in glyphs: out.append("    { %d, %d, %d, %d, %d, %d }," % g)
        out.append("};")
        fonts.append("    { %d, %d, %s_glyphs, %s_data }," % (size, asc + desc, name, name))
    out.append("const LfFont lf_fonts[%d] = {" % len(SIZES))
    out += fonts
    out.append("};")
    print("\n".join(out))

main()
