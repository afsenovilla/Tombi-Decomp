#!/usr/bin/env python3
"""bin2c.py FILE OUT.c NAME: FILE as `const unsigned char NAME[]` and `const unsigned NAME_size` (the 3DS build carries
the improved Spanish translation's compiled patch this way: port2/CMakeLists.txt, port2/n3ds/main_3ds.c)."""
import sys
src, out, name = sys.argv[1:4]
d = open(src, "rb").read()
with open(out, "w") as f:
    f.write("/* generated by port2/tools/bin2c.py from %s */\n" % src.replace("\\", "/").split("/")[-1])
    f.write("const unsigned %s_size = %d;\nconst unsigned char %s[] = {\n" % (name, len(d), name))
    for i in range(0, len(d), 24):
        f.write(",".join(str(b) for b in d[i:i + 24]) + ",\n")
    f.write("};\n")
