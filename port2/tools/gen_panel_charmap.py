#!/usr/bin/env python3
"""Writes port2/runtime/panel_charmap.h for the second-screen panel (runtime/panel_assets.c): which character each WFM glyph
bitmap of the game's fonts is, as tools/wfm_charmap.json records it (height, width, the first 6 bytes of the SHA-1 of the
glyph's 4 bpp image -> character).  Only hashes and Latin-1 codes: no glyph bitmaps.  The panel reads the glyphs from the
user's disc (AREAnn/MFNTnnnL.WFM, CFNT999L.WFM; USA: the banks inside the area GAM files) and names them with this table.
The USA disc's retouched glyphs come from tools/wfm_charmap_usa.json (tools/wfm_charmap_usa.py), after the PAL ones.

  python3 port2/tools/gen_panel_charmap.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def main():
    m = json.load(open(os.path.join(ROOT, "tools/wfm_charmap.json"), encoding="utf-8"))
    # then the USA disc's retouched glyphs (tools/wfm_charmap_usa.py), after the PAL ones
    usa = json.load(open(os.path.join(ROOT, "tools/wfm_charmap_usa.json"), encoding="utf-8"))
    rows = []
    for k, ch in sorted(m.items()) + sorted((k, v) for k, v in usa.items() if k not in m):
        h, w, sha = k.split(":")
        c = ord(ch)
        if c > 255 or c < 32:
            continue
        rows.append("{%s,%s,{%s},%d}" % (h, w, ",".join("0x" + sha[i:i + 2] for i in range(0, 12, 2)), c))
    out = ["/* generated by port2/tools/gen_panel_charmap.py from tools/wfm_charmap.json (+ _usa.json): WFM glyph (height, width, SHA-1[0..5] of",
           "   its 4 bpp image) -> Latin-1 character.  Hashes only, no game data. */",
           "typedef struct { unsigned char h, w, sha[6]; unsigned char ch; } PanelCharKey;",
           "static const PanelCharKey panel_charmap[] = {"]
    for i in range(0, len(rows), 4):
        out.append("    " + ", ".join(rows[i:i + 4]) + ",")
    out.append("};")
    open(os.path.join(ROOT, "port2/runtime/panel_charmap.h"), "w").write("\n".join(out) + "\n")
    print(len(rows), "glyph keys")


if __name__ == "__main__":
    main()
