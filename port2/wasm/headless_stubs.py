#!/usr/bin/env python3
"""headless_stubs.py W2CDIR OUT.c: a host without SDL / GL (port2/wasm/build.py --headless-host, e.g. the aarch64 Linux
binary run under qemu-user to check the arm64 host code): every import of module "port" except the coroutine switch
returns 0 (runtime/sdl.c's entry points: no window, no audio device; the GL ones are never reached headless)."""
import re, sys
h = open(sys.argv[1] + "/tombi.h").read()
out = ['/* generated by port2/wasm/headless_stubs.py: no SDL window / GL on this host (--headless only) */', '#include "tombi.h"']
for name, proto in re.findall(r"/\* import: 'port' '(\w+)' \*/\n([^\n]+);", h):
    if name == "ctx_switch": continue
    m = re.match(r"(\w+) (w2c_port_\w+)\((.*)\)$", proto)
    ret, fn, args = m.groups()
    params = ", ".join("%s a%d" % (t.strip(), i) for i, t in enumerate(args.split(",")))
    out.append("%s %s(%s) { %s }" % (ret, fn, params, "" if ret == "void" else "return 0;"))
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("headless_stubs: %d imports stubbed" % (len(out) - 2))
